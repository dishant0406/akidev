"""Write the design token files of both phone apps from content/manga/tokens.json.

Run `python3 content/manga/generate.py` to write the files.
Run `python3 content/manga/generate.py --check` to exit 1 when a file on disk is out of date.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
TOKENS_PATH = os.path.join(HERE, "tokens.json")
SWIFT_PATH = os.path.join(REPO, "apps", "manga-ios", "App", "UI", "Generated", "TokenValues.swift")
KOTLIN_PATH = os.path.join(REPO, "apps", "manga-android", "design", "src", "main", "kotlin",
                           "live", "akidev", "manga", "design", "AkiTokenValues.kt")
HEADER = "Generated by content/manga/generate.py from content/manga/tokens.json: do not edit."

# These two opacities are the primary color at that opacity. The other opacities are black at that opacity.
ON_PRIMARY = ("accent", "accentSoft")


def load_tokens():
    with open(TOKENS_PATH, encoding="utf-8") as f:
        return json.load(f)


def hex_digits(value):
    return value.lstrip("#").upper()


def capitalize(name):
    return name[0].upper() + name[1:]


def swift_color(value):
    if isinstance(value, dict):
        return "adaptive(0x%s, 0x%s)" % (hex_digits(value["light"]), hex_digits(value["dark"]))
    return "Color(hex: 0x%s)" % hex_digits(value)


def swift_text(tokens):
    lines = ["import SwiftUI", "", "extension Aki {"]
    for name, value in tokens["colors"].items():
        lines.append("    static let %s = %s" % (name, swift_color(value)))
    lines.append("")
    for name, value in tokens["opacities"].items():
        base = "primary" if name in ON_PRIMARY else "Color(hex: 0x000000)"
        lines.append("    static let %s = %s.opacity(%.2f)" % (name, base, value))
    lines.append("")
    for name, value in tokens["radii"].items():
        lines.append("    static let %sRadius: CGFloat = %d" % (name, value))
    lines.append("}")
    return "\n".join(["// " + HEADER] + lines) + "\n"


def kotlin_text(tokens):
    lines = [
        "package live.akidev.manga.design",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.dp",
        "",
        "internal object AkiTokenValues {",
    ]
    for name, value in tokens["colors"].items():
        if isinstance(value, dict):
            lines.append("    val light%s = Color(0xFF%s)" % (capitalize(name), hex_digits(value["light"])))
            lines.append("    val dark%s = Color(0xFF%s)" % (capitalize(name), hex_digits(value["dark"])))
        else:
            lines.append("    val %s = Color(0xFF%s)" % (name, hex_digits(value)))
    lines.append("")
    for name, value in tokens["opacities"].items():
        lines.append("    const val %sOpacity = %.2ff" % (name, value))
    lines.append("")
    for name, value in tokens["radii"].items():
        lines.append("    val %sRadius = %d.dp" % (name, value))
    lines.append("}")
    return "\n".join(["// " + HEADER] + lines) + "\n"


def read_or_none(path):
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return f.read()


def relative(path):
    return os.path.relpath(path, REPO)


def main():
    tokens = load_tokens()
    files = [(SWIFT_PATH, swift_text(tokens)), (KOTLIN_PATH, kotlin_text(tokens))]

    if "--check" not in sys.argv:
        for path, text in files:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print("wrote", relative(path))
        return

    stale = [path for path, text in files if read_or_none(path) != text]
    for path in stale:
        print("out of date:", relative(path))
    if stale:
        sys.exit(1)
    print("generated files are up to date")


if __name__ == "__main__":
    main()
